#!/usr/bin/env bash
set -euo pipefail

# Vendor the CRDs of a cert-manager release into crds/, as compact JSON plus an index
# (crds/main.libsonnet) and the version they came from (crds/VERSION).
#   ./generate.sh v1.19.1
# Needs helm and yq. The tags in images.libsonnet must match (tests check it).
version="${1:?usage: generate.sh <version, e.g. v1.19.1>}"
cd "$(dirname "${BASH_SOURCE[0]}")"

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
helm template cert-manager cert-manager \
  --repo https://charts.jetstack.io --version "$version" \
  --set crds.enabled=true --set crds.keep=false \
  > "$tmp/all.yaml"

rm -rf crds && mkdir crds
# Collapse the generated files in GitHub diffs and language stats.
printf '# Generated by generate.sh.\n* linguist-generated=true\n' > crds/.gitattributes
yq -o=json -I=0 -s '"crds/" + .metadata.name + ".json"' 'select(.kind == "CustomResourceDefinition")' "$tmp/all.yaml"
{
  echo "// Generated by generate.sh. Do not edit."
  echo "{"
  for f in crds/*.json; do
    n="$(basename "$f" .json)"
    echo "  '$n': import '$n.json',"
  done
  echo "}"
} > crds/main.libsonnet
printf '%s' "$version" > crds/VERSION

