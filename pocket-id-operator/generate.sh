#!/usr/bin/env bash
set -euo pipefail

# Vendor the CRDs of a pocket-id-operator release into crds/, as compact JSON plus an index
# (crds/main.libsonnet) and the version they came from (crds/VERSION).
#   ./generate.sh v0.16.2
# Needs curl and yq. The image tag in images.libsonnet must match (tests check it).
version="${1:?usage: generate.sh <version, e.g. v0.16.2>}"
cd "$(dirname "${BASH_SOURCE[0]}")"

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
curl -sfL "https://github.com/aclerici38/pocket-id-operator/releases/download/$version/install.yaml" > "$tmp/all.yaml"

rm -rf crds && mkdir crds
# Collapse the generated files in GitHub diffs and language stats.
printf '# Generated by generate.sh.\n* linguist-generated=true\n' > crds/.gitattributes
yq -o=json -I=0 -s '"crds/" + .metadata.name + ".json"' 'select(.kind == "CustomResourceDefinition")' "$tmp/all.yaml"
{
  echo "// Generated by generate.sh. Do not edit."
  echo "{"
  for f in crds/*.json; do
    n="$(basename "$f" .json)"
    echo "  '$n': import '$n.json',"
  done
  echo "}"
} > crds/main.libsonnet
printf '%s' "$version" > crds/VERSION
