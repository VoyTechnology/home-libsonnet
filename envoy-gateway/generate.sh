#!/usr/bin/env bash
set -euo pipefail

# Vendor the Envoy CRDs (gateway.envoyproxy.io) of a gateway-helm chart release into crds/, as compact
# JSON plus an index (crds/main.libsonnet) and the chart version they came from (crds/VERSION).
# The Gateway API CRDs the chart also ships are left out (k3s installs them).
#   ./generate.sh v1.7.0
# Needs helm and yq. The image tags in images.libsonnet are the chart's appVersion.
version="${1:?usage: generate.sh <chart version, e.g. v1.7.0>}"
cd "$(dirname "${BASH_SOURCE[0]}")"

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
helm template envoy oci://docker.io/envoyproxy/gateway-helm --version "$version" \
  -n envoy-gateway-system --include-crds > "$tmp/all.yaml"

rm -rf crds && mkdir crds
# Collapse the generated files in GitHub diffs and language stats.
printf '# Generated by generate.sh.\n* linguist-generated=true\n' > crds/.gitattributes
yq -o=json -I=0 -s '"crds/" + .metadata.name + ".json"' 'select(.kind == "CustomResourceDefinition" and .spec.group == "gateway.envoyproxy.io")' "$tmp/all.yaml"
{
  echo "// Generated by generate.sh. Do not edit."
  echo "{"
  for f in crds/*.json; do
    n="$(basename "$f" .json)"
    echo "  '$n': import '$n.json',"
  done
  echo "}"
} > crds/main.libsonnet
printf '%s' "$version" > crds/VERSION
