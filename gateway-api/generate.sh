#!/usr/bin/env bash
set -euo pipefail

# Vendor the Gateway API CRDs of a release into crds/, as compact JSON plus an index
# (crds/main.libsonnet) and the release they came from (crds/VERSION).
#   ./generate.sh v1.6.3 [experimental|standard]
# Needs curl and yq.
version="${1:?usage: generate.sh <release, e.g. v1.6.3> [experimental|standard]}"
channel="${2:-experimental}"
cd "$(dirname "${BASH_SOURCE[0]}")"

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
curl -fsSL "https://github.com/kubernetes-sigs/gateway-api/releases/download/${version}/${channel}-install.yaml" > "$tmp/all.yaml"

rm -rf crds && mkdir crds
# Collapse the generated files in GitHub diffs and language stats.
printf '# Generated by generate.sh.\n* linguist-generated=true\n' > crds/.gitattributes
yq -o=json -I=0 -s '"crds/" + .metadata.name + ".json"' 'select(.kind == "CustomResourceDefinition")' "$tmp/all.yaml"
{
  echo "// Generated by generate.sh. Do not edit."
  echo "{"
  for f in crds/*.json; do
    n="$(basename "$f" .json)"
    echo "  '$n': import '$n.json',"
  done
  echo "}"
} > crds/main.libsonnet
printf '%s %s' "$version" "$channel" > crds/VERSION
