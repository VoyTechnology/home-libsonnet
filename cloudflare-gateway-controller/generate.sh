#!/usr/bin/env bash
set -euo pipefail

# Vendor the CRDs of a cloudflare-gateway-controller release into crds/, as compact JSON plus an index
# (crds/main.libsonnet) and the version they came from (crds/VERSION).
#   ./generate.sh v0.16.0
# The project only ships a Helm chart, so the CRDs come from its templates. The Gateway API CRDs it
# bundles are skipped, they belong to whatever provides the Gateway API (envoy-gateway here).
# Needs git, helm and yq. The image tag in images.libsonnet must match (tests check it).
version="${1:?usage: generate.sh <version, e.g. v0.16.0>}"
cd "$(dirname "${BASH_SOURCE[0]}")"

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
git clone -q --depth 1 --branch "$version" https://github.com/matheuscscp/cloudflare-gateway-controller.git "$tmp/src"
helm template cgc "$tmp/src/charts/cloudflare-gateway-controller" --set config.clusterName=x --set image.tag="$version" > "$tmp/all.yaml"

rm -rf crds && mkdir crds
# Collapse the generated files in GitHub diffs and language stats.
printf '# Generated by generate.sh.\n* linguist-generated=true\n' > crds/.gitattributes
yq -o=json -I=0 -s '"crds/" + .metadata.name + ".json"' \
  'select(.kind == "CustomResourceDefinition" and .spec.group == "cloudflare-gateway-controller.io")' "$tmp/all.yaml"
{
  echo "// Generated by generate.sh. Do not edit."
  echo "{"
  for f in crds/*.json; do
    n="$(basename "$f" .json)"
    echo "  '$n': import '$n.json',"
  done
  echo "}"
} > crds/main.libsonnet
printf '%s' "$version" > crds/VERSION
