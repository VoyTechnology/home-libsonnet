#!/usr/bin/env bash
set -euo pipefail

# Vendor the CRDs of an metallb chart release into crds/, as compact JSON plus an
# index (crds/main.libsonnet) and the chart version they came from (crds/VERSION).
#   ./generate.sh 0.15.2
# Needs helm and yq. The image tag in images.libsonnet is the chart's appVersion.
version="${1:?usage: generate.sh <chart version, e.g. 0.15.2>}"
cd "$(dirname "${BASH_SOURCE[0]}")"

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
helm template metallb metallb \
  --repo https://metallb.github.io/metallb --version "$version" -n metallb-system --include-crds > "$tmp/all.yaml"

rm -rf crds && mkdir crds
# Collapse the generated files in GitHub diffs and language stats.
printf '# Generated by generate.sh.\n* linguist-generated=true\n' > crds/.gitattributes
yq -o=json -I=0 -s '"crds/" + .metadata.name + ".json"' 'select(.kind == "CustomResourceDefinition")' "$tmp/all.yaml"
{
  echo "// Generated by generate.sh. Do not edit."
  echo "{"
  for f in crds/*.json; do
    n="$(basename "$f" .json)"
    echo "  '$n': import '$n.json',"
  done
  echo "}"
} > crds/main.libsonnet
printf '%s' "$version" > crds/VERSION
